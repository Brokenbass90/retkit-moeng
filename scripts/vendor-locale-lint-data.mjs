// Generates src/shared/locale-lint-data.js: trigram language models taken from
// franc-all (MIT © Titus Wormer), trimmed to the languages of RetKit locales.
// Run once when the language list changes:  npm i --no-save franc-all@7 && node scripts/vendor-locale-lint-data.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgPath = require.resolve('franc-all/package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
const { data } = await import(pathToFileURL(path.join(path.dirname(pkgPath), 'data.js')).href);

// Only the languages RetKit locales are written in: detection then answers
// "which of OUR languages does this text look like", not "which of 400".
const WANT = {
  Latin: ['eng', 'deu', 'spa', 'fra', 'ita', 'nld', 'nob', 'swe', 'tur', 'ind', 'zlm', 'tgl', 'vie', 'azj', 'por'],
  Cyrillic: ['rus', 'ukr'],
  Arabic: ['arb', 'urd'],
  Devanagari: ['hin'],
};
const out = {};
for (const [script, langs] of Object.entries(WANT)) {
  out[script] = {};
  for (const lang of langs) {
    const model = data?.[script]?.[lang];
    if (!model) throw new Error(`franc-all has no ${script}/${lang}`);
    out[script][lang] = model;
  }
}
const banner = `/*! RetKit locale-lint language models — GENERATED by scripts/vendor-locale-lint-data.mjs, do not edit.
 *  Trigram models from franc-all ${pkg.version} (https://github.com/wooorm/franc),
 *  MIT License, Copyright (c) 2014 Titus Wormer <tituswormer@gmail.com>.
 *  The models are built from the Universal Declaration of Human Rights (copyright-free).
 *  Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated
 *  documentation files (the "Software"), to deal in the Software without restriction, including without limitation
 *  the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to
 *  permit persons to whom the Software is furnished to do so, subject to the following conditions: The above copyright
 *  notice and this permission notice shall be included in all copies or substantial portions of the Software.
 *  THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED.
 */
`;
const body = `(function (root) {\n  'use strict';\n  root.RetKitLocaleLintData = ${JSON.stringify({ source: `franc-all ${pkg.version}`, models: out })};\n  if (typeof module !== 'undefined' && module.exports) module.exports = root.RetKitLocaleLintData;\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
const target = path.join(root, 'src/shared/locale-lint-data.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, banner + body);
console.log(`✓ ${path.relative(root, target)} — ${Object.values(out).reduce((n, s) => n + Object.keys(s).length, 0)} languages, ${(fs.statSync(target).size / 1024).toFixed(1)} KB`);
